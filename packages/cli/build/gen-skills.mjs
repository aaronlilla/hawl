// Copies the four Hawl skills from plugins/claude-code/skills (the one source) into
// src/hosts/skills-data.ts, so the single-file CLI build can write them on join.
// Usage: node build/gen-skills.mjs   (skills.test.ts fails when the output is stale)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const names = [
  "hawl-coordinate",
  "hawl-delegate",
  "hawl-verify",
  "hawl-handover",
];
const src = join(root, "../../plugins/claude-code/skills");
const body = names
  .map(
    (n) =>
      `  ${JSON.stringify(n)}: ${JSON.stringify(readFileSync(join(src, n, "SKILL.md"), "utf8"))},`,
  )
  .join("\n");
writeFileSync(
  join(root, "src/hosts/skills-data.ts"),
  `// Generated by build/gen-skills.mjs from plugins/claude-code/skills. Do not edit.\nexport const SKILLS: Record<string, string> = {\n${body}\n};\n`,
);
